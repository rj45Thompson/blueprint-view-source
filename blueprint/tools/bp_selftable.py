#!/usr/bin/env python3
"""bp_selftable.py - which engine functions take `self` for an unwired object pin, READ from their UFUNCTION metadata.

The compiler rule (CallFunctionHandler.cpp:747-757, FKCHandler_CallFunction::RegisterNets): an input pin with no wire and no default
object, named by the function's DefaultToSelf metadata, is compiled as a literal whose sub-category is self - the Blueprint's own
object. The pasted text never says which pin that is (it is metadata on the C++ declaration, measured 2026-10-28: a Lock-On paste's
K2_SetTimer Object pin is a plain object pin, no default), so the converter printed `null` where the engine runs `this`. This reads
every `DefaultToSelf = "Pin"` in the engine's Runtime headers and the function it is declared on.

    py -X utf8 tools/bp_selftable.py      # writes view/bp_self.js

Every entry keeps the header line it came from. A UFUNCTION whose declaration cannot be read after its metadata is refused, never
skipped.
"""
import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.dirname(HERE)
import ue_engine  # noqa: E402  the engine UE_ROOT names, and its version
UE = ue_engine.root()
RUNTIME = UE + "/Engine/Source/Runtime"
META = re.compile(r'DefaultToSelf\s*=\s*"?(\w+)"?')
DECL = re.compile(r"(?:static\s+)?(?:virtual\s+)?(?:[A-Z]+_API\s+)?(?:FORCEINLINE\s+)?[\w:<>,\s\*&]+?\s+(\w+)\s*\(")
CLASS = re.compile(r"^\s*class\s+(?:[A-Z]+_API\s+)?([UA]\w+)\s*(?::|$|\{)", re.M)


def scan():
    out = {}
    files = 0
    for root, _, names in os.walk(RUNTIME):
        for n in names:
            if not n.endswith(".h"):
                continue
            p = os.path.join(root, n).replace("\\", "/")
            text = io.open(p, encoding="utf-8", errors="replace").read()
            if "DefaultToSelf" not in text:
                continue
            files += 1
            lines = text.split("\n")
            for i, line in enumerate(lines):
                if "UFUNCTION" not in line or "DefaultToSelf" not in line:
                    # a UFUNCTION may span lines: join it up to its closing paren
                    if "UFUNCTION" not in line:
                        continue
                block = line
                j = i
                while block.count("(") > block.count(")") and j + 1 < len(lines):
                    j += 1
                    block += " " + lines[j].strip()
                m = META.search(block)
                if not m:
                    continue
                # the declaration: the next non-blank line(s) that read as a function
                decl = ""
                k = j + 1
                while k < len(lines) and len(decl) < 600:
                    decl += " " + lines[k].strip()
                    if "(" in decl:
                        break
                    k += 1
                d = DECL.search(decl)
                if not d:
                    raise SystemExit("bp_selftable: %s:%d has DefaultToSelf=%s and no readable declaration after it" % (p, i + 1, m.group(1)))
                cls = [c for c in CLASS.finditer(text[: sum(len(x) + 1 for x in lines[:i])])]
                owner = cls[-1].group(1)[1:] if cls else "?"
                key = "%s.%s" % (owner, d.group(1))
                out[key] = {"param": m.group(1), "at": "%s:%d" % (p.split("/Source/")[1], i + 1)}
    return out, files


def main():
    table, files = scan()
    if not table:
        sys.exit("bp_selftable: no DefaultToSelf found under %s - an empty table proves nothing" % RUNTIME)
    js = ("// bp_self.js - generated by tools/bp_selftable.py from %s: engine functions whose unwired object pin is `self`\n"
          "// (DefaultToSelf; compiled as self by CallFunctionHandler.cpp:747-757), each with the header line it was read from.\n"
          "// Never edit by hand; regenerate.\nvar BP_SELF = %s;\nif (typeof module !== 'undefined' && module.exports) module.exports = BP_SELF;\n"
          % (ue_engine.version(UE) + ", Engine/Source/Runtime", json.dumps(table, indent=0, sort_keys=True)))
    io.open(os.path.join(EXP, "view", "bp_self.js"), "w", encoding="utf-8", newline="\n").write(js)
    print("bp_selftable: %d functions in %d headers -> view/bp_self.js (e.g. KismetSystemLibrary.K2_SetTimer: %s)" % (
        len(table), files, table.get("KismetSystemLibrary.K2_SetTimer")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
