#!/usr/bin/env python3
"""loop_report.py - LoopReport: one paste set's closed loop measured twice and written to results/LOOP_<SET>.md - the node as it
stood before 10-28 (the same model with its effects, terms and loop meta stripped) and the node now.

The question it answers: is the requirement node's structure ideal? The criteria for an ideal node name the pieces a perfectly
closed loop of requirements would still be missing. The criteria are autobot/usecase_kg.LOOP; the difference between the two
runs IS the missing pieces, measured by the gate rather than listed by hand. Every figure on the page is read from the two runs.

    py -X utf8 tools/loop_report.py <set dir> "<title>"      (after `u2ue blueprint build <set dir>`: it reads trace/verdicts.json)

Exit 1 when the loop on the set has a hole of ours (the report is still written: it says so).
"""
import glob
import io
import os
import re
import shutil
import subprocess
import sys
import tempfile

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import toolkit_home  # noqa: E402  the toolkit's home, in its own tree or a release
KG = os.path.normpath(toolkit_home.tool("autobot", "usecase_kg.py"))
ROW = re.compile(r"^  (L\d+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(.*?)(\s+\[not held\])?$")


def loop(model, verdicts=None):
    cmd = [sys.executable, "-X", "utf8", KG, "loop", model, "--max", "40"] + (["--verdicts", verdicts] if verdicts else [])
    r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return r.returncode, r.stdout + r.stderr


def rows(out):
    """criterion id -> (name, ours, owner, listed, mistake, held)"""
    got = {}
    for line in out.splitlines():
        m = ROW.match(line)
        if m:
            got[m.group(1)] = (m.group(2), m.group(3), m.group(4), m.group(5), m.group(6), m.group(7) is None)
    if not got:
        raise SystemExit("loop_report: the gate printed no criteria table:\n" + out[-600:])
    return got


def stripped(set_dir):
    """a copy of the set whose model has no effect, no term and no loop meta: the node as it stood before 10-28"""
    tmp = tempfile.mkdtemp(prefix="loop_before_")
    md = os.path.join(tmp, "model")
    os.makedirs(md)
    for f in glob.glob(os.path.join(set_dir, "model", "*.yaml")):
        d = yaml.safe_load(io.open(f, encoding="utf-8")) or {}
        d.pop("terms", None)
        (d.get("meta") or {}).pop("loop", None)
        for r in d.get("requirements") or []:
            r.pop("effect", None)
        io.open(os.path.join(md, os.path.basename(f)), "w", encoding="utf-8").write(yaml.safe_dump(d, sort_keys=False, allow_unicode=True))
    shutil.copytree(os.path.join(set_dir, "trace"), os.path.join(tmp, "trace"))   # the code spaces read ../trace and ../*.t3d
    for f in glob.glob(os.path.join(set_dir, "*.t3d")):
        shutil.copy(f, tmp)
    return tmp


def section(out, head):
    """the gate's lines under one `Ln NAME, KIND: n` heading"""
    lines, take = [], False
    for line in out.splitlines():
        if line.startswith("  L"):
            take = line.strip().startswith(head)
            continue
        if take and line.startswith("      "):
            lines.append(line.strip())
    return lines


def main(argv):
    if len(argv) < 1:
        sys.exit(__doc__)
    set_dir = argv[0].rstrip("/\\")
    title = argv[1] if len(argv) > 1 else os.path.basename(set_dir)
    verdicts = os.path.join(set_dir, "trace", "verdicts.json")
    if not os.path.exists(verdicts):
        print("loop_report: no %s - run `py -m u2ue blueprint build %s` first (the code adapter writes it)" % (verdicts, set_dir))
        return 2
    code, after = loop(os.path.join(set_dir, "model"), verdicts)
    tmp = stripped(set_dir)
    try:
        _, before = loop(os.path.join(tmp, "model"))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    # the stripped copy's temp folder is a machine path that changes every run: the page names what it is instead
    for p in (os.path.join(tmp, "model"), os.path.join(tmp, "model").replace("\\", "/")):
        before = before.replace(p, "<this model, stripped of effects, terms and loop meta>")
    a, b = rows(after), rows(before)
    missing = [c for c in sorted(a, key=lambda x: int(x[1:])) if not b[c][5]]
    verdict = next((ln.strip() for ln in after.splitlines() if ln.strip().startswith("LOOP ")), "")
    caught = section(after, "L7 REALIZED, OWNER")
    o = ["# The closed loop: %s" % title, "",
         "GENERATED by tools/loop_report.py from two runs of `autobot/usecase_kg.py loop` - never edit by hand.", "",
         "Closed-loop requirements replace the code as what an AI acts on: it works from the loop rather than from prompts, so no "
         "mistake gets through unless the requirements themselves carry it. Each criterion below is one way a mistake gets past the "
         "requirements; the gate counts the holes it finds: OURS (the model's author closes them), OWNER (only the requirements' owner "
         "can), listed (shown, not failing).",
         "", "**Verdict now:** %s" % verdict, "",
         "## Each criterion, before and after", "",
         "BEFORE is this model with its effects, terms and loop meta stripped: the node as it stood before 10-28. A criterion it could "
         "not hold at all is a missing piece of the node.", "",
         "| criterion | the mistake it stops | before | after: ours / owner / listed |", "|---|---|---|---|"]
    for c in sorted(a, key=lambda x: int(x[1:])):
        name, ours, owner, listed, mistake, _ = a[c]
        bn = b[c]
        o.append("| %s %s | %s | %s | %s / %s / %s |" % (c, name, mistake, "NOT HELD - the node had no field for it" if not bn[5]
                                                          else "%s / %s / %s" % bn[1:4], ours, owner, listed))
    o += ["", "## The missing pieces (%d of %d criteria the node could not hold)" % (len(missing), len(a)), ""]
    o += ["- **%s %s**: %s" % (c, a[c][0], a[c][4]) for c in missing]
    o += ["", "Each one became measurable through one addition to the node: the requirement's EFFECT (assertions in the code's own "
          "terms: sets, calls, branches or reads, at a statement, an outcome or a graph; `sets X by F` for a write through a call), "
          "its TERMS (each word bound to the code names it means), and the LOCK (each requirement's fingerprint as last verified).", "",
          "## What the loop caught in the code (%d owner holes in L7)" % len(caught), "",
          "Each is a requirement the chain needs and the code as pasted does not meet, or a design call only the owner can make:", ""]
    o += ["- %s" % x for x in caught]
    o += ["", "## The gate's own words", "", "After:", "", "```", after.rstrip(), "```", "", "Before (stripped):", "", "```", before.rstrip(), "```", ""]
    name = re.sub(r"\W+", "_", os.path.basename(set_dir)).upper()
    path = os.path.join(EXP, "results", "LOOP_%s.md" % name)
    os.makedirs(os.path.dirname(path), exist_ok=True)      # a fresh clone holds no results/ until a build writes one (10-28)
    io.open(path, "w", encoding="utf-8", newline="\n").write("\n".join(o))
    print("loop_report: %d criteria; %d missing before; %s -> %s" % (len(a), len(missing), verdict, os.path.relpath(path, EXP)))
    return 1 if "LOOP BROKEN" in verdict else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
