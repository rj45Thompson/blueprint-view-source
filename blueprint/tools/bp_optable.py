#!/usr/bin/env python3
"""bp_optable.py - the Blueprint converter's operator table, READ from the engine (BC-3: "the operator table is READ from the
engine's KismetMathLibrary metadata, not written by hand").

An engine math function whose UFUNCTION meta names a CompactNodeTitle that is an operator (+, ==, AND, ...) is drawn as that
operator in Blueprint; the converter prints it as the operator too. Every entry keeps the header line it came from.

    py -X utf8 tools/bp_optable.py      # writes view/bp_ops.js

A Blueprint AND / OR takes both inputs as a function does (pure inputs are all evaluated before the call), so it becomes C#'s
`&` / `|`, never the short-circuit `&&` / `||`, which would skip an input Blueprint evaluates.
"""
import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import ue_engine  # noqa: E402  the engine UE_ROOT names, and its version
UE = ue_engine.root()
ENGINE = UE + "/Engine/Source/Runtime/Engine/Classes/Kismet"
HEADERS = ("KismetMathLibrary.h", "KismetStringLibrary.h", "KismetTextLibrary.h")
# CompactNodeTitle -> the operator printed (binary / unary decided by the function's parameter count)
TITLES = {"+": "+", "-": "-", "*": "*", "/": "/", "%": "%", "==": "==", "!=": "!=", "<": "<", ">": ">", "<=": "<=", ">=": ">=",
          "&": "&", "|": "|", "^": "^", "~": "~", "AND": "&", "OR": "|", "XOR": "^", "NOT": "!"}
DECL = re.compile(r"static\s+(?:UE_\w+\s+)*(?:FORCEINLINE\s+)?([\w:<>,\s\*&]+?)\s+(\w+)\s*\(([^)]*)\)")


def read(path):
    out = {}
    lines = io.open(path, encoding="utf-8", errors="replace").read().split("\n")
    for i, line in enumerate(lines):
        m = re.search(r'CompactNodeTitle\s*=\s*"([^"]*)"', line)
        if not m or m.group(1) not in TITLES or "UFUNCTION" not in line:
            continue
        # the declaration follows the UFUNCTION line (sometimes after a blank or a comment line)
        for j in range(i + 1, min(i + 4, len(lines))):
            d = DECL.search(lines[j])
            if d:
                params = [p for p in d.group(3).split(",") if p.strip()]
                out[d.group(2)] = {"op": TITLES[m.group(1)], "arity": len(params), "title": m.group(1),
                                   "at": "%s:%d" % (os.path.basename(path), j + 1)}
                break
        else:
            raise ValueError("%s:%d names CompactNodeTitle %r but no declaration follows within 3 lines" % (path, i + 1, m.group(1)))
    return out


def main():
    table = {}
    for h in HEADERS:
        p = os.path.join(ENGINE, h)
        if not os.path.exists(p):
            raise FileNotFoundError("the engine header %s is not on this machine - the table cannot be READ" % p)
        table.update(read(p))
    target = os.path.join(EXP, "view", "bp_ops.js")
    io.open(target, "w", encoding="utf-8", newline="\n").write(
        "// bp_ops.js - generated by tools/bp_optable.py from %s (%s): engine math functions drawn as operators in Blueprint,\n"
        "// each with the header line it was read from. Never edit by hand; regenerate.\n"
        "var BP_OPS = %s;\nif (typeof module !== 'undefined' && module.exports) module.exports = BP_OPS;\n"
        % (ue_engine.version(UE) + ", Engine/Source/Runtime/Engine/Classes/Kismet", ", ".join(HEADERS), json.dumps(table, indent=0, sort_keys=True)))
    by = {}
    for v in table.values():
        by[v["op"]] = by.get(v["op"], 0) + 1
    print("bp_optable: %d functions read as operators from %s -> %s" % (len(table), ", ".join(HEADERS), target))
    print("  " + ", ".join("%s %d" % (k, n) for k, n in sorted(by.items(), key=lambda x: -x[1])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
